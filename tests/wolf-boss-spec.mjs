import assert from 'node:assert/strict';
import { WolfBossSystem as W } from '../js/core/WolfBossSystem.js';
import { EnemyAI } from '../js/core/EnemyAI.js';
import { SkillSystem } from '../js/core/SkillSystem.js';
import { wolfBoss, wolfBattleSkills as skills } from '../js/data/enemies.js';

const makeWolf = () => W.initialize({id:0,spriteKey:'wolf',role:'WOLF',hp:1200,maxHp:1200,thresholds:[840,480,180],staggerLevel:0,staggered:false,staggerTurns:0});
const slots = [{index:0,unitId:'don',speed:6},{index:1,unitId:'don',speed:3},{index:2,unitId:'don',speed:5},{index:3,unitId:'don',speed:4}];
const intents = (w,turn) => EnemyAI.buildIntents({enemies:[w],turn,donSlots:slots,randomInt:min=>min,rng:()=>.1,getSkillPool:()=>[]});
assert.equal(wolfBoss.maxHp,1200);
assert.deepEqual(wolfBoss.staggerThresholds,[840,480,180]);
assert.deepEqual(wolfBoss.speed,[4,7]);
for (const [key, base, cp, coins] of [['sever',4,5,1],['indigoBlade',4,4,2],['azureRend',5,3,3]]) {
 assert.deepEqual([skills[key].base,skills[key].coinPower,skills[key].coins],[base,cp,coins]);
}
let w = makeWolf();
assert.equal(intents(w,1).map(i=>i.skill.key).join(','),'sever,sever,indigoBlade');
assert.equal(intents(w,2).map(i=>i.skill.key).join(','),'sever,sever,indigoBlade');
assert.equal(intents(w,3).map(i=>i.skill.key).join(','),'azureRend,azureRend,shimmeringCleave');
assert.deepEqual(intents(w,3)[0].targetSlotIndices,[1]);
assert.equal(intents(w,4)[0].skill.key,'sever');
assert.ok(intents(w,3).every(i=>i.speed===4));
W.beginTurn(w,[w]); assert.equal(w.clashPowerUp,1);
W.updatePassive(w,[w,{hp:1}]); assert.equal(w.clashPowerUp,0);
W.updatePassive(w,[w,{hp:0}]); assert.equal(w.clashPowerUp,1);
w.hp=840; assert.ok(W.checkStagger(w)); assert.equal(w.staggerTurns,2);
assert.equal(w.staggerLevel,1); assert.equal(W.checkStagger(w),false);
w.hp=480; W.checkStagger(w); assert.equal(W.canUseMirage(w),false);
w.hp=479; W.checkStagger(w); assert.ok(w.miragePhasePending);
assert.equal(intents(w,4)[0].skill.key,'sever','Stagger delays Mirage');
w.staggered=false;
let list=intents(w,4);
assert.equal(list[0].skill.key,'mirageSlash');
assert.equal(new Set(list[0].targetSlotIndices).size,3);
assert.equal(w.mirageForcedUsed,false,'UI rebuilding must not consume the forced skill');
W.markSkillUsed(w,skills.mirageSlash); assert.equal(w.mirageForcedUsed,true);
assert.equal(intents(w,5)[0].skill.key,'sever');
assert.equal(intents(w,6)[0].skill.key,'mirageSlash');
w.hp=600; assert.equal(intents(w,6)[0].skill.key,'azureRend','Healing above phase blocks Mirage');
w=makeWolf(); w.hp=100;
assert.ok(W.checkStagger(w)); assert.equal(w.staggerLevel,3,'One hit consumes every crossed threshold');
assert.equal(W.checkStagger(w),false,'No stale threshold can re-stagger next hit');
assert.equal(W.missingHpCoinPowerBonus({hp:240,maxHp:1200}),4);
assert.equal(W.missingHpCoinPowerBonus({hp:1,maxHp:1200}),4);
assert.equal(W.missingHpCoinPowerBonus({hp:1200,maxHp:1200}),0);
const d={exhaust:0}; W.addExhaust(d,3); W.decayExhaustTurnEnd(d);
assert.equal(d.exhaust,2); W.applyExhaustTurnStart(d);
assert.equal(d.offenseLevelDown,3,'Exactly 3 before decay must still apply next-turn debuff');
assert.equal(d.exhaust,0); W.decayExhaustTurnEnd(d); W.applyExhaustTurnStart(d);
assert.equal(d.offenseLevelDown,0,'Debuff lasts one turn');
W.addExhaust(d,99); assert.equal(d.exhaust,5); W.applyExhaustTurnStart(d);
assert.equal(d.exhaust,2); assert.deepEqual(W.playerSpeedRange(d),[3,4]);
assert.deepEqual(W.playerSpeedRange({exhaust:5}),[3,3]);
w=makeWolf(); w.hp=400; W.changeSp(w,-99);
assert.equal(w.sp,-45); assert.ok(w.panicPending); assert.equal(w.panicActive,false);
W.beginTurn(w); assert.ok(w.panicActive); assert.equal(intents(w,3)[0].skill.key,'azureRend');
assert.equal(SkillSystem.basePower(skills.azureRend,{unit:w}),3);
W.endTurn(w); assert.equal(w.sp,0); assert.equal(w.panicActive,false);
w.sp=0; W.onClashEnd(w,skills.azureRend,true); assert.equal(w.sp,20,'Normal +10 and Azure +10 once per full Clash');
W.onClashEnd(w,skills.mirageSlash,false); assert.equal(w.nextFragile,1);
W.beginTurn(w); assert.equal(w.fragile,1); W.endTurn(w); assert.equal(w.fragile,0);
const units=[{id:'don',hp:203},{id:'other',hp:10}];
assert.deepEqual(EnemyAI.uniqueTargetUnits([0,1,2],slots,units),[units[0]],'Three slots on Don must not triple AoE hits');
console.log('Wolf boss spec: PASS');
